"""Generate web/backdrop.html: the animated gold and violet background.

    python tools/make_backdrop.py

The background is split into layers (gold strands, violet waves, violet glow)
plus small floating gold flakes, so the browser can move each piece as a whole
without redrawing it. That keeps the animation light even with glow effects.
All shapes are drawn from maths here; nothing is copied from elsewhere.
"""
import math
import random
from pathlib import Path

W, H = 1600, 1000
OUT = Path(__file__).resolve().parent.parent / "web" / "backdrop.html"

DEFS = """<defs>
<linearGradient id="bd-gold" x1="0" y1="0" x2="1" y2="1">
 <stop offset="0" stop-color="#6e4f12"/><stop offset=".45" stop-color="#e2b33c"/>
 <stop offset=".7" stop-color="#f6dc8a"/><stop offset="1" stop-color="#8a6516"/>
</linearGradient>
<linearGradient id="bd-violet" x1="0" y1="1" x2="1" y2="0">
 <stop offset="0" stop-color="#5b1a9e"/><stop offset=".5" stop-color="#b347ff"/><stop offset="1" stop-color="#d9a6ff"/>
</linearGradient>
<filter id="bd-glow" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="9"/></filter>
</defs>"""


def path(pts):
    return "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts)


def curve(f, n=240):
    return [f(i / (n - 1)) for i in range(n)]


def layer(cls, body, view=f"0 0 {W} {H}", style=""):
    return (f'<svg class="bd-layer {cls}" viewBox="{view}" preserveAspectRatio="xMidYMid slice" '
            f'style="{style}" aria-hidden="true" focusable="false">{body}</svg>')


def main():
    parts = []
    # Gold strands: a sweeping S-curve made of parallel threads.
    gold = '<g fill="none" stroke="url(#bd-gold)" stroke-linecap="round">'
    for k in range(-6, 7):
        def f(u, k=k):
            x = -160 + u * (W + 320)
            y = 620 + 170 * math.sin(u * math.pi * 1.6 + 0.4) + k * 7 + 60 * math.sin(u * 9 + k * 0.3) * u
            return (x, y)
        op = max(0.85 - abs(k) * 0.11, 0.12)
        gold += f'<path d="{path(curve(f))}" stroke-width="{1.4 if k == 0 else 0.8}" opacity="{op:.2f}"/>'
    gold += "</g>"
    parts.append(layer("bd-gold", gold))

    # Violet waves: crisp cores and a separate glow layer that pulses.
    waves = []
    for a, b, c, d in [(330, 140, 1.3, 2.6), (820, 110, 2.1, 0.9)]:
        waves.append(path(curve(lambda u, a=a, b=b, c=c, d=d: (-160 + u * (W + 320), a + b * math.sin(u * math.pi * c + d)))))
    core = '<g fill="none" stroke="url(#bd-violet)" stroke-linecap="round">' + "".join(
        f'<path d="{d}" stroke-width="1.8"/>' for d in waves) + "</g>"
    glow = '<g fill="none" stroke="url(#bd-violet)" stroke-linecap="round" filter="url(#bd-glow)">' + "".join(
        f'<path d="{d}" stroke-width="10"/>' for d in waves) + "</g>"
    parts.append(layer("bd-waves", core))
    parts.append(layer("bd-waves bd-glow", glow))

    # Gold flakes: small irregular shards that float and catch the light.
    rng = random.Random(7)  # fixed seed: the same flakes every time
    flakes = []
    for i in range(46):
        size = rng.choice([4, 5, 5, 6, 6, 7, 8, 9, 11, 14])
        corners = rng.randint(4, 6)
        pts = []
        for k in range(corners):
            ang = 2 * math.pi * k / corners + rng.uniform(-0.35, 0.35)
            r = rng.uniform(0.55, 1.0) * 50
            pts.append(f"{50 + r * math.cos(ang):.0f}% {50 + r * math.sin(ang):.0f}%")
        style = (f"left:{rng.uniform(2, 98):.2f}%;top:{rng.uniform(3, 97):.2f}%;"
                 f"--s:{size}px;--r:{rng.randint(0, 359)}deg;"
                 f"--shape:polygon({', '.join(pts)});"
                 f"--float:{rng.uniform(14, 30):.1f}s;--twinkle:{rng.uniform(3.5, 8):.1f}s;"
                 f"--delay:-{rng.uniform(0, 30):.1f}s;--dx:{rng.uniform(-28, 28):.0f}px;"
                 f"--dy:{rng.uniform(-40, -12):.0f}px;--peak:{rng.uniform(0.9, 1.0):.2f}")
        flakes.append(f'<i class="bd-flake" style="{style}"></i>')
    parts.append('<div class="bd-flakes">' + "".join(flakes) + "</div>")

    html = ('<!-- Generated by tools/make_backdrop.py. Edit that file, not this one. -->\n'
            '<div class="backdrop" aria-hidden="true">'
            '<svg class="bd-defs" width="0" height="0" focusable="false">' + DEFS + '</svg>'
            '<div class="bd-haze"></div><div class="bd-board">\n'
            + "\n".join(parts) + "\n</div></div>\n")
    OUT.write_text(html, encoding="utf-8")
    print(f"wrote {OUT} ({len(html) // 1024} KB)")


if __name__ == "__main__":
    main()
